create extension if not exists pgcrypto;

create table if not exists public.staff_roles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  role text not null check (role in ('owner'))
);
create table if not exists public.menu_items (
  id bigint generated by default as identity primary key,
  name text not null check (length(trim(name)) between 1 and 100),
  category text not null,
  price numeric(10,2) not null check (price>=0),
  emoji text not null default '🍽️',
  description text not null default '',
  active boolean not null default true,
  created_at timestamptz not null default now()
);
create table if not exists public.restaurant_tables (
  code text primary key,
  active boolean not null default true
);
create sequence if not exists public.mori_order_seq start 1025;
create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  number text not null unique default ('A-'||nextval('public.mori_order_seq')),
  table_code text not null references public.restaurant_tables(code),
  track_token uuid not null unique default gen_random_uuid(),
  total numeric(10,2) not null default 0,
  status text not null default 'waiting' check(status in ('waiting','cooking','ready','served','cancelled')),
  payment_status text not null default 'unpaid' check(payment_status in ('unpaid','paid')),
  created_at timestamptz not null default now()
);
create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.orders(id) on delete cascade,
  menu_id bigint,
  name text not null,
  emoji text not null,
  price numeric(10,2) not null,
  qty integer not null check (qty between 1 and 99)
);
create index if not exists idx_mori_order_items on public.order_items(order_id);
create index if not exists idx_mori_orders_created on public.orders(created_at desc);

create or replace function public.mori_is_owner() returns boolean
language sql security definer stable set search_path = '' as $$
  select exists(select 1 from public.staff_roles where user_id=(select auth.uid()) and role='owner')
$$;

alter table public.staff_roles enable row level security;
alter table public.menu_items enable row level security;
alter table public.restaurant_tables enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;

create policy "owner sees own role" on public.staff_roles for select to authenticated using (user_id=(select auth.uid()));
create policy "public reads active menus owner reads all" on public.menu_items for select to anon,authenticated using (active or public.mori_is_owner());
create policy "owner inserts menu" on public.menu_items for insert to authenticated with check (public.mori_is_owner());
create policy "owner updates menu" on public.menu_items for update to authenticated using (public.mori_is_owner()) with check (public.mori_is_owner());
create policy "owner deletes menu" on public.menu_items for delete to authenticated using (public.mori_is_owner());
create policy "public reads available tables" on public.restaurant_tables for select to anon,authenticated using (active or public.mori_is_owner());
create policy "owner reads orders" on public.orders for select to authenticated using (public.mori_is_owner());
create policy "owner updates orders" on public.orders for update to authenticated using (public.mori_is_owner()) with check (public.mori_is_owner());
create policy "owner reads items" on public.order_items for select to authenticated using (public.mori_is_owner());
-- Order inserts / updates by customers happen only via server-side RPC below.

create or replace function public.place_order(p_table text,p_items jsonb) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  v_id uuid; v_token uuid; v_number text; v_total numeric(10,2):=0;
  v_item jsonb; v_menu public.menu_items%rowtype; v_qty int; v_count int:=0;
begin
  if not exists(select 1 from public.restaurant_tables where code=p_table and active=true) then
    raise exception 'Invalid table';
  end if;
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) not between 1 and 60 then
    raise exception 'Invalid order items';
  end if;
  insert into public.orders(table_code) values(p_table) returning id,track_token,number into v_id,v_token,v_number;
  for v_item in select value from jsonb_array_elements(p_items) as x(value) loop
    if not(v_item ? 'id' and v_item ? 'qty') then raise exception 'Invalid item'; end if;
    v_qty:=(v_item->>'qty')::int;
    if v_qty<1 or v_qty>99 then raise exception 'Invalid quantity'; end if;
    select * into v_menu from public.menu_items where id=(v_item->>'id')::bigint and active=true;
    if not found then raise exception 'Menu unavailable'; end if;
    insert into public.order_items(order_id,menu_id,name,emoji,price,qty)
    values(v_id,v_menu.id,v_menu.name,v_menu.emoji,v_menu.price,v_qty);
    v_total:=v_total+(v_menu.price*v_qty);v_count:=v_count+v_qty;
  end loop;
  if v_count>120 then raise exception 'Too many items'; end if;
  update public.orders set total=v_total where id=v_id;
  return jsonb_build_object('order_id',v_id,'track_token',v_token,'number',v_number);
end $$;

create or replace function public.track_order(p_token uuid) returns jsonb
language sql security definer stable set search_path = '' as $$
  select jsonb_build_object('number',o.number,'table_code',o.table_code,'total',o.total,
     'status',o.status,'payment_status',o.payment_status,'created_at',o.created_at,
     'items',coalesce((select jsonb_agg(jsonb_build_object('name',i.name,'qty',i.qty))
                       from public.order_items i where i.order_id=o.id),'[]'::jsonb))
  from public.orders o where o.track_token=p_token
$$;

create or replace function public.owner_edit_order(p_order_id uuid,p_items jsonb) returns void
language plpgsql security definer set search_path = '' as $$
declare
  v_item jsonb; v_menu public.menu_items%rowtype; v_qty int; v_total numeric(10,2):=0; v_count int:=0;
begin
  if not public.mori_is_owner() then raise exception 'Not authorized'; end if;
  if not exists(select 1 from public.orders where id=p_order_id and status<>'cancelled' for update) then
    raise exception 'Order not found or cancelled';
  end if;
  if jsonb_typeof(p_items)<>'array' or jsonb_array_length(p_items) not between 1 and 60 then
    raise exception 'Invalid items';
  end if;
  delete from public.order_items where order_id=p_order_id;
  for v_item in select value from jsonb_array_elements(p_items) as x(value) loop
    v_qty:=(v_item->>'qty')::int;
    if v_qty<1 or v_qty>99 then raise exception 'Invalid quantity'; end if;
    select * into v_menu from public.menu_items where id=(v_item->>'id')::bigint;
    if not found then raise exception 'Menu not found'; end if;
    insert into public.order_items(order_id,menu_id,name,emoji,price,qty)
    values(p_order_id,v_menu.id,v_menu.name,v_menu.emoji,v_menu.price,v_qty);
    v_total:=v_total+v_menu.price*v_qty;v_count:=v_count+v_qty;
  end loop;
  if v_count>120 then raise exception 'Too many items'; end if;
  update public.orders set total=v_total where id=p_order_id;
end $$;

